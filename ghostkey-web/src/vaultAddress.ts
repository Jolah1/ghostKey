/**
 * Derive a vault's address in the browser, from its descriptor (#378).
 *
 * The deposit address the owner pays into comes from our server. If the
 * server were ever compromised it could hand back an attacker's address,
 * and the owner's savings would go there instead of into their vault.
 * This lets the browser work the address out itself and compare.
 *
 * It understands exactly the descriptor shapes GhostKey builds (see
 * ghostkey-core/src/descriptor.rs): `tr(NUMS, <one tapscript leaf>)` whose
 * leaf uses pk, v:pk, s:pk, older, v:older, v:after, and_v, or_d and
 * or_b. Anything else throws `UnsupportedDescriptor` rather than guessing.
 * It is checked against addresses generated by the Rust code itself
 * (src/fixtures/vault-addresses.json, written by
 * crates/ghostkey-wasm/tests/address_fixtures.rs), so the two can't drift
 * apart silently.
 *
 * Pure JS on libraries the app already ships (@scure/bip32 and its
 * curves), instead of the 5 MB wasm module the recovery kit uses.
 */
import { HDKey } from "@scure/bip32";
import { secp256k1, schnorr } from "@noble/curves/secp256k1.js";
import { bech32m } from "@scure/base";

export class UnsupportedDescriptor extends Error {}

type Node =
  | { t: "pk"; key: string }
  | { t: "older"; n: number }
  | { t: "after"; n: number }
  | { t: "and_v"; a: Node; b: Node }
  | { t: "or_d"; a: Node; b: Node }
  | { t: "or_b"; a: Node; b: Node }
  | { t: "wrap"; w: "v" | "s"; x: Node };

/* ------------------------------- parsing -------------------------------- */

function parseNode(src: string): Node {
  let i = 0;
  const fail = (why: string): never => {
    throw new UnsupportedDescriptor(`${why} at ${i}`);
  };
  const readName = () => {
    const m = /^[a-z_]+/.exec(src.slice(i));
    if (!m) fail("expected a fragment");
    i += m![0].length;
    return m![0];
  };
  const expect = (c: string) => {
    if (src[i] !== c) fail(`expected '${c}'`);
    i += 1;
  };
  const readUntilClose = () => {
    const start = i;
    while (i < src.length && src[i] !== ")" && src[i] !== ",") i += 1;
    return src.slice(start, i);
  };
  const node = (): Node => {
    const name = readName();
    if (src[i] === ":") {
      // Wrappers: "v:", "s:". Applied right to left.
      i += 1;
      const wrappers = name.split("");
      const inner = node();
      return wrappers.reduceRight<Node>((x, w) => {
        if (w !== "v" && w !== "s") fail(`unsupported wrapper ${w}`);
        return { t: "wrap", w: w as "v" | "s", x };
      }, inner);
    }
    expect("(");
    let out: Node;
    switch (name) {
      case "pk":
        out = { t: "pk", key: readUntilClose() };
        break;
      case "older":
      case "after": {
        const n = Number(readUntilClose());
        if (!Number.isSafeInteger(n) || n <= 0) fail(`bad number in ${name}`);
        out = { t: name, n };
        break;
      }
      case "and_v":
      case "or_d":
      case "or_b": {
        const a = node();
        expect(",");
        const b = node();
        out = { t: name, a, b };
        break;
      }
      default:
        return fail(`unsupported fragment ${name}`);
    }
    expect(")");
    return out;
  };
  const root = node();
  if (i !== src.length) fail("trailing input");
  return root;
}

/** Split `tr(INTERNAL,LEAF)` (checksum optional) into its two parts. */
/** The internal key and the script leaves: one leaf, or a two-leaf tree
 *  `{A,B}` (a locked goal's owner and heir branches). */
function splitTr(descriptor: string): { internal: string; leaves: Node[] } {
  const d = descriptor.replace(/#[a-z0-9]+$/, "");
  if (!d.startsWith("tr(") || !d.endsWith(")")) {
    throw new UnsupportedDescriptor("not a tr() descriptor");
  }
  const body = d.slice(3, -1);
  const comma = body.indexOf(",");
  if (comma < 0) throw new UnsupportedDescriptor("tr() without a script leaf");
  const internal = body.slice(0, comma);
  const tree = body.slice(comma + 1);
  if (!tree.startsWith("{")) return { internal, leaves: [parseNode(tree)] };
  if (!tree.endsWith("}")) throw new UnsupportedDescriptor("unclosed tree");
  const inner = tree.slice(1, -1);
  // Split at the one comma that isn't inside brackets.
  let depth = 0;
  let split = -1;
  for (let i = 0; i < inner.length; i++) {
    const c = inner[i];
    if (c === "(" || c === "{") depth += 1;
    else if (c === ")" || c === "}") depth -= 1;
    else if (c === "," && depth === 0) {
      if (split >= 0) throw new UnsupportedDescriptor("only two-leaf trees are supported");
      split = i;
    }
  }
  if (split < 0) throw new UnsupportedDescriptor("a tree needs two leaves");
  const a = inner.slice(0, split);
  const b = inner.slice(split + 1);
  if (a.startsWith("{") || b.startsWith("{")) throw new UnsupportedDescriptor("nested trees aren't supported");
  return { internal, leaves: [parseNode(a), parseNode(b)] };
}

/* -------------------------------- keys ---------------------------------- */

const XPUB_VERSIONS: Record<string, { private: number; public: number }> = {
  xpub: { private: 0x0488ade4, public: 0x0488b21e },
  tpub: { private: 0x04358394, public: 0x043587cf },
};

function hexToBytes(hex: string): Uint8Array {
  if (!/^[0-9a-f]*$/i.test(hex) || hex.length % 2) {
    throw new UnsupportedDescriptor("bad hex key");
  }
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}

/** The x-only key for one descriptor key at a wildcard index. */
function xOnlyKey(key: string, index: number): Uint8Array {
  // Raw 32-byte x-only hex (the NUMS internal key).
  if (/^[0-9a-f]{64}$/i.test(key)) return hexToBytes(key);
  // [fingerprint/path]xpub.../chain/*
  const m = /^(?:\[[0-9a-f]{8}(?:\/\d+'?)*\])?((?:xpub|tpub)[1-9A-HJ-NP-Za-km-z]+)((?:\/\d+)*)\/\*$/.exec(
    key,
  );
  if (!m) throw new UnsupportedDescriptor(`unsupported key ${key.slice(0, 16)}…`);
  const versions = XPUB_VERSIONS[m[1].slice(0, 4)];
  let hd = HDKey.fromExtendedKey(m[1], versions);
  for (const step of m[2].split("/").filter(Boolean)) hd = hd.deriveChild(Number(step));
  const pub = hd.deriveChild(index).publicKey;
  if (!pub) throw new UnsupportedDescriptor("key has no public key");
  return pub.slice(1);
}

/* ------------------------------ compiling ------------------------------- */

const OP = {
  CHECKSIG: 0xac,
  CHECKSIGVERIFY: 0xad,
  CSV: 0xb2,
  CLTV: 0xb1,
  VERIFY: 0x69,
  SWAP: 0x7c,
  IFDUP: 0x73,
  NOTIF: 0x64,
  ENDIF: 0x68,
  BOOLOR: 0x9b,
};

/** Minimal script-number push, as Bitcoin Core and miniscript emit it. */
function pushNumber(n: number): number[] {
  if (n >= 1 && n <= 16) return [0x50 + n];
  const bytes: number[] = [];
  let v = n;
  while (v > 0) {
    bytes.push(v & 0xff);
    v = Math.floor(v / 256);
  }
  if (bytes[bytes.length - 1] & 0x80) bytes.push(0x00);
  return [bytes.length, ...bytes];
}

function compile(node: Node, index: number): number[] {
  switch (node.t) {
    case "pk":
      return [32, ...xOnlyKey(node.key, index), OP.CHECKSIG];
    case "older":
      return [...pushNumber(node.n), OP.CSV];
    case "after":
      return [...pushNumber(node.n), OP.CLTV];
    case "and_v":
      return [...compile(node.a, index), ...compile(node.b, index)];
    case "or_d":
      return [
        ...compile(node.a, index),
        OP.IFDUP,
        OP.NOTIF,
        ...compile(node.b, index),
        OP.ENDIF,
      ];
    case "or_b":
      return [...compile(node.a, index), ...compile(node.b, index), OP.BOOLOR];
    case "wrap": {
      const inner = compile(node.x, index);
      if (node.w === "s") return [OP.SWAP, ...inner];
      // v: folds a trailing CHECKSIG into CHECKSIGVERIFY, else adds VERIFY.
      if (inner[inner.length - 1] === OP.CHECKSIG) {
        return [...inner.slice(0, -1), OP.CHECKSIGVERIFY];
      }
      return [...inner, OP.VERIFY];
    }
  }
}

/* ------------------------------- taproot -------------------------------- */

function compactSize(n: number): number[] {
  if (n < 0xfd) return [n];
  if (n <= 0xffff) return [0xfd, n & 0xff, n >> 8];
  throw new UnsupportedDescriptor("script too long");
}

function compareBytes(a: Uint8Array, b: Uint8Array): number {
  for (let i = 0; i < Math.min(a.length, b.length); i++) {
    if (a[i] !== b[i]) return a[i] - b[i];
  }
  return a.length - b.length;
}

const HRP: Record<string, string> = {
  bitcoin: "bc",
  testnet: "tb",
  signet: "tb",
  regtest: "bcrt",
};

/** The vault's address on `network`, for the receive (`descriptor` is the
 *  external one) or change chain, at wildcard `index`. */
export function deriveVaultAddress(descriptor: string, network: string, index: number): string {
  const hrp = HRP[network];
  if (!hrp) throw new UnsupportedDescriptor(`unknown network ${network}`);
  const { internal, leaves } = splitTr(descriptor);

  const leafHashes = leaves.map((leaf) => {
    const script = Uint8Array.from(compile(leaf, index));
    return schnorr.utils.taggedHash(
      "TapLeaf",
      Uint8Array.from([0xc0, ...compactSize(script.length), ...script]),
    );
  });
  // One leaf is its own root; two meet in a TapBranch of the pair, in
  // byte order (BIP 341).
  let root = leafHashes[0];
  if (leafHashes.length === 2) {
    const [x, y] = leafHashes;
    const xFirst = compareBytes(x, y) <= 0;
    root = schnorr.utils.taggedHash("TapBranch", xFirst ? x : y, xFirst ? y : x);
  }
  const internalX = xOnlyKey(internal, index);
  const tweak = schnorr.utils.taggedHash("TapTweak", internalX, root);
  const P = secp256k1.Point.fromHex("02" + Array.from(internalX, (b) => b.toString(16).padStart(2, "0")).join(""));
  const t = BigInt("0x" + Array.from(tweak, (b) => b.toString(16).padStart(2, "0")).join(""));
  const Q = P.add(secp256k1.Point.BASE.multiply(t));
  const outputKey = Q.toBytes(true).slice(1);

  return bech32m.encode(hrp, [1, ...bech32m.toWords(outputKey)]);
}
