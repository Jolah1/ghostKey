// Package the ghostkey-wasm artifact for the offline recovery kit.
//
// The kit is a single self-contained HTML file, so the wasm cannot be
// fetched at runtime — it must be inlined. This script takes the
// wasm-pack output and emits two files under src/kit/wasm/:
//
//   - ghostkey_wasm.js   the wasm-bindgen JS glue (copied verbatim)
//   - wasmBase64.ts      the .wasm bytes as a base64 string constant
//
// signer.ts loads the glue and instantiates it from the base64 bytes, so
// no network is ever touched. Run automatically before the kit build
// (see package.json `build:kit`).
//
// Prereq: `wasm-pack build crates/ghostkey-wasm --target web --release`
// has produced crates/ghostkey-wasm/pkg/. That step needs clang +
// wasm-pack and is run separately (it is not part of the Vercel build).

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const pkgDir = join(webRoot, "..", "crates", "ghostkey-wasm", "pkg");
const outDir = join(webRoot, "src", "kit", "wasm");

const glueSrc = join(pkgDir, "ghostkey_wasm.js");
const wasmSrc = join(pkgDir, "ghostkey_wasm_bg.wasm");

if (!existsSync(glueSrc) || !existsSync(wasmSrc)) {
  console.error(
    `\n[bundle-kit-wasm] missing wasm-pack output at ${pkgDir}\n` +
      `Run this first (needs clang + wasm-pack):\n` +
      `  wasm-pack build crates/ghostkey-wasm --target web --release\n`,
  );
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

// Glue + its type declarations, copied verbatim.
writeFileSync(join(outDir, "ghostkey_wasm.js"), readFileSync(glueSrc));
const dtsSrc = join(pkgDir, "ghostkey_wasm.d.ts");
if (existsSync(dtsSrc)) writeFileSync(join(outDir, "ghostkey_wasm.d.ts"), readFileSync(dtsSrc));

// Wasm bytes as a base64 constant.
const b64 = readFileSync(wasmSrc).toString("base64");
const ts =
  `// Generated by scripts/bundle-kit-wasm.mjs — do not edit.\n` +
  `// The ghostkey-wasm binary, base64-encoded for offline inlining.\n` +
  `export const WASM_BASE64 =\n  "${b64}";\n`;
writeFileSync(join(outDir, "wasmBase64.ts"), ts);

const kib = Math.round(readFileSync(wasmSrc).length / 1024);
console.log(`[bundle-kit-wasm] wrote src/kit/wasm/ (wasm ${kib} KiB -> base64 ${Math.round(b64.length / 1024)} KiB)`);
